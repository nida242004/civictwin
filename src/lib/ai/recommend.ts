/**
 * Deterministic planning recommendations — the no-LLM fallback.
 * These are computed from actual application metrics and geometry,
 * not generated text. Clearly labeled as rule-based.
 */

import type { PraesidiumProject } from "../world/types";
import type { Proposal, ProposalOp } from "./schema";
import { applyOutages, computeCoverage, COVERAGE_SAMPLE_STEP_M } from "../sim/scenarios";
import type { StoredRun } from "../world/types";
import { outcomeLabel } from "../sim/labels";

export interface RecommendationResult {
  proposal: Proposal;
  basis: string[];
}

/** Rule-based intervention proposal derived from coverage + run metrics. */
export function deterministicRecommendation(project: PraesidiumProject, baselineRun: StoredRun | null): RecommendationResult {
  const { world, scenario } = project;
  const outages = applyOutages(world, scenario.lightingOutageFraction, scenario.seed);
  const effLights = world.streetlights.map((l) => (outages.has(l.id) ? { ...l, on: false } : l));
  const coverage = computeCoverage({ ...world, streetlights: effLights }, scenario.ambientVisibility, scenario.cctvRangeScale);
  const basis: string[] = [];

  const ops: ProposalOp[] = [];

  // 1. find the darkest walkable segments by sampling coverage per road
  const perRoad: { roadId: string; litFrac: number; mid: { x: number; z: number } | null }[] = [];
  for (const road of world.roads) {
    if (!road.pedestrian) continue;
    const litFrac = coverage.perRoadLit.get(road.id) ?? 0;
    const mid = road.points.length >= 2 ? road.points[Math.floor(road.points.length / 2)] : null;
    perRoad.push({ roadId: road.id, litFrac, mid });
  }
  const darkest = perRoad.filter((r) => r.litFrac < 0.6 && r.mid).sort((a, b) => a.litFrac - b.litFrac).slice(0, 5);
  for (const d of darkest) {
    if (!d.mid) continue;
    ops.push({ op: "add_streetlight", x: round1(d.mid.x), z: round1(d.mid.z), brightness: 0.9, radius: 19 });
  }
  if (darkest.length) {
    basis.push(
      `${darkest.length} walkable path${darkest.length > 1 ? "s" : ""} are modeled below 60% lit coverage; streetlights are proposed at their midpoints.`
    );
  }

  // 2. CCTV gap: if coverage < 25%, propose a camera near the busiest pedestrian area
  const cctvPct = coverage.totalLenM > 0 ? (coverage.cctvLenM / coverage.totalLenM) * 100 : 0;
  if (cctvPct < 25) {
    const dest = world.facilities.find((f) => f.type === "bus_stop") ?? world.facilities[0];
    if (dest) {
      ops.push({
        op: "add_camera",
        x: round1(dest.x + 6),
        z: round1(dest.z + 6),
        range: 32,
        fovDeg: 90,
        orientationDeg: 225,
      });
      basis.push(`Modeled CCTV coverage is ${cctvPct.toFixed(1)}% — a camera is proposed near "${dest.name ?? dest.type}" (a modeled pedestrian destination).`);
    }
  }

  // 3. guard response: unresolved events with long/no response → suggest patrol via hotspot
  if (baselineRun) {
    const unresolved = baselineRun.events.filter((e) => e.outcome !== "resolved");
    if (unresolved.length > 0 && world.guards.length > 0) {
      const cx = avg(unresolved.map((e) => e.x));
      const cz = avg(unresolved.map((e) => e.z));
      const g = world.guards[0];
      ops.push({
        op: "set_patrol",
        guardId: g.id,
        waypoints: [
          { x: round1(g.waypoints[0]?.x ?? cx), z: round1(g.waypoints[0]?.z ?? cz) },
          { x: round1(cx), z: round1(cz) },
          { x: round1(g.waypoints[1]?.x ?? cx + 20), z: round1(g.waypoints[1]?.z ?? cz + 20) },
        ],
      });
      const byOutcome = new Map<string, number>();
      for (const e of unresolved) byOutcome.set(e.outcome, (byOutcome.get(e.outcome) ?? 0) + 1);
      const breakdown = Array.from(byOutcome.entries())
        .map(([o, n]) => `${n} × ${outcomeLabel(o).toLowerCase()}`)
        .join(", ");
      basis.push(
        `${unresolved.length} simulated event${unresolved.length > 1 ? "s" : ""} were not resolved in the baseline run (${breakdown}); ${g.name}'s patrol is redirected through their modeled cluster.`
      );
    }
    const avgResp = baselineRun.metrics.avgResponseSec;
    if (avgResp !== null && avgResp > 180 && world.guards.length < 2) {
      basis.push(`Estimated average response time is ${Math.round(avgResp)} s — consider a second guard (scenario parameter) or a closer patrol route.`);
    }
  } else {
    basis.push("Run a baseline simulation first — patrol and response recommendations will then use your actual run results.");
  }

  if (!ops.length) {
    ops.push({ op: "add_streetlight", x: 0, z: 0, brightness: 0.9, radius: 19 });
    basis.push("No clear gaps were detected from current metrics — a starter streetlight at the neighborhood center is proposed as a neutral first intervention.");
  }

  return {
    proposal: {
      title: "Rule-based improvement plan (deterministic)",
      rationale:
        "This proposal was generated by Praesidium's built-in rule-based analyzer from your project's computed coverage and simulation metrics — no AI model was involved. It targets the darkest walkable paths and modeled coverage gaps first.",
      ops,
      expectedEffects: [
        "Higher modeled lit-path coverage",
        cctvPct < 25 ? "Higher modeled CCTV coverage near a pedestrian destination" : "Wider modeled camera coverage",
        "Possibly shorter estimated guard response times on affected routes",
      ],
      limitations: [
        "Based on simplified geometric coverage assumptions, not a photometric or criminological analysis",
        "Run the intervention with the same seed to obtain a genuine comparison",
      ],
      costNotes: undefined,
    },
    basis,
  };
}

function avg(arr: number[]): number {
  return arr.length ? arr.reduce((a, b) => a + b, 0) / arr.length : 0;
}

function round1(v: number): number {
  return Math.round(v * 10) / 10;
}

export { COVERAGE_SAMPLE_STEP_M };
