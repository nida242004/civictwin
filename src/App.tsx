import React, { useState, useMemo, useCallback } from 'react';
import confetti from 'canvas-confetti';
import { Sliders, BarChart3 } from 'lucide-react';
import { Header } from './components/Header';
import { NeighborhoodCanvas } from './components/canvas/NeighborhoodCanvas';
import { PolicyToolbar } from './components/policy/PolicyToolbar';
import { CivicDashboard } from './components/dashboard/CivicDashboard';
import { CitizenInspectorModal } from './components/inspector/CitizenInspectorModal';
import { GeminiPolicyAdvisorModal } from './components/dashboard/GeminiPolicyAdvisorModal';
import { TimeScrubber } from './components/controls/TimeScrubber';
import { ArchitectToolbar, type ArchitectTool } from './components/canvas/ArchitectToolbar';
import { SCENARIO_1, AVAILABLE_POLICIES } from './simulation/scenarios';
import { simulateCitizen } from './simulation/behaviorEngine';
import { calculateAggregateMetrics } from './simulation/metricsCalculator';
import type { PolicyId, AggregateMetrics } from './types/policy';
import type { Position, DistrictGrid, Amenity, TransitRoute } from './types/urban';
import type { CitizenPersona, CitizenSimResult } from './types/citizen';
import { INITIAL_PERPS, type PerpPersona } from './types/perp';

export function App() {
  const scenario = SCENARIO_1;

  // Custom citizens generated by Gemini
  const [customCitizens, setCustomCitizens] = useState<CitizenPersona[]>([]);
  const allCitizens = useMemo(
    () => [...scenario.citizens, ...customCitizens],
    [scenario.citizens, customCitizens]
  );

  // Policies active in the sandbox
  const [activePolicyIds, setActivePolicyIds] = useState<PolicyId[]>([
    'STREETLIGHT_NETWORK',
    'NIGHT_BUS_ROUTE',
    'ACCESSIBLE_PUBLIC_TOILETS',
  ]);

  // Mode: BASELINE (status quo) vs POLICY (sandbox) vs COMPARISON (A/B view)
  const [mode, setMode] = useState<'BASELINE' | 'POLICY' | 'COMPARISON'>('POLICY');

  // Sidebar view tab: 'POLICIES' or 'DASHBOARD'
  const [sidebarTab, setSidebarTab] = useState<'POLICIES' | 'DASHBOARD'>('POLICIES');

  // Gemini Advisor Modal state
  const [isGeminiModalOpen, setIsGeminiModalOpen] = useState<boolean>(false);

  // Time & playback state
  const [currentHour, setCurrentHour] = useState<number>(scenario.defaultHour);
  const [isPlaying, setIsPlaying] = useState<boolean>(false);
  const [speed, setSpeed] = useState<number>(1);
  const [viewMode, setViewMode] = useState<'REALISTIC' | 'FEAR_HEATMAP' | 'FOOT_TRAFFIC'>('REALISTIC');

  // Selected citizen for inspection modal
  const [selectedCitizenId, setSelectedCitizenId] = useState<string | null>(null);

  // Urban Architect tool & user-placed features
  const [selectedTool, setSelectedTool] = useState<ArchitectTool>('INSPECT');
  const [userPlacedAmenities, setUserPlacedAmenities] = useState<Amenity[]>([]);
  const [perps, setPerps] = useState<PerpPersona[]>(INITIAL_PERPS);

  // Toggle a policy
  const handleTogglePolicy = (id: PolicyId) => {
    setActivePolicyIds((prev) =>
      prev.includes(id) ? prev.filter((p) => p !== id) : [...prev, id]
    );
  };

  // Quick apply recommended policy bundle
  const handleApplyRecommended = () => {
    setActivePolicyIds(scenario.recommendedPolicies);
    confetti({
      particleCount: 50,
      spread: 60,
      origin: { y: 0.8 },
    });
  };

  // Construct Policy District Grid
  const policyGrid = useMemo<DistrictGrid>(() => {
    const baseGrid = scenario.district;
    const amenities: Amenity[] = [...baseGrid.amenities, ...userPlacedAmenities];
    const transitRoutes: TransitRoute[] = [...baseGrid.transitRoutes];

    // If Streetlight Network policy enabled, add streetlights along the dark alley and corridors
    if (activePolicyIds.includes('STREETLIGHT_NETWORK')) {
      const alleyLights: Amenity[] = [
        {
          id: 'policy-lamp-1',
          type: 'STREETLIGHT',
          position: { x: 5, y: 2 },
          radius: 2.5,
          activeHours: [18, 6],
          name: 'Alley Light North',
          description: 'High-output LED streetlight',
          capex: 1200,
          monthlyOpex: 24,
          isPolicyAdded: true,
        },
        {
          id: 'policy-lamp-2',
          type: 'STREETLIGHT',
          position: { x: 5, y: 5 },
          radius: 2.5,
          activeHours: [18, 6],
          name: 'Alley Light Mid',
          description: 'High-output LED streetlight',
          capex: 1200,
          monthlyOpex: 24,
          isPolicyAdded: true,
        },
        {
          id: 'policy-lamp-3',
          type: 'STREETLIGHT',
          position: { x: 10, y: 4 },
          radius: 2.5,
          activeHours: [18, 6],
          name: 'Residential Walkway Lamp',
          description: 'High-output LED streetlight',
          capex: 1200,
          monthlyOpex: 24,
          isPolicyAdded: true,
        },
      ];
      amenities.push(...alleyLights);
    }

    // If Public Toilets policy enabled, add accessible pod at Metro Plaza
    if (activePolicyIds.includes('ACCESSIBLE_PUBLIC_TOILETS')) {
      amenities.push({
        id: 'policy-restroom-1',
        type: 'PUBLIC_TOILET',
        position: { x: 3, y: 11 },
        radius: 1.5,
        activeHours: [0, 24],
        name: 'Metro Plaza Restroom Pod',
        description: 'Universal wheelchair-accessible self-cleaning restroom',
        capex: 18000,
        monthlyOpex: 450,
        isPolicyAdded: true,
      });
    }

    // If Community Safety Kiosk enabled
    if (activePolicyIds.includes('COMMUNITY_SAFETY_KIOSK')) {
      amenities.push({
        id: 'policy-kiosk-1',
        type: 'POLICE_KIOSK',
        position: { x: 8, y: 8 },
        radius: 3.5,
        activeHours: [19, 5],
        name: 'Central Safety Intercom Kiosk',
        description: 'Auxiliary patrol and emergency call point',
        capex: 6500,
        monthlyOpex: 350,
        isPolicyAdded: true,
      });
    }

    // If Night Bus Route enabled, extend Route #4 hours to 03:00
    if (activePolicyIds.includes('NIGHT_BUS_ROUTE')) {
      transitRoutes.push({
        id: 'night-owl-bus',
        name: 'Owl Night Bus Route #4 (21:00 - 03:00)',
        stops: [
          { x: 2, y: 12 },
          { x: 7, y: 8 },
          { x: 12, y: 8 },
          { x: 12, y: 2 },
        ],
        activeHours: [21, 3], // midnight wrap
        headwayMinutes: 15,
        monthlyOpex: 3800,
        color: '#10b981',
        isPolicyAdded: true,
      });
    }

    return {
      ...baseGrid,
      amenities,
      transitRoutes,
    };
  }, [scenario.district, activePolicyIds, userPlacedAmenities]);

  // Baseline Grid (No policy additions)
  const baselineGrid = scenario.district;

  // Run Simulation for Baseline
  const baselineResults = useMemo<CitizenSimResult[]>(() => {
    return allCitizens.map((c) => simulateCitizen(c, baselineGrid, c.departureTime, perps));
  }, [allCitizens, baselineGrid, perps]);

  // Run Simulation for Policy District
  const policyResults = useMemo<CitizenSimResult[]>(() => {
    return allCitizens.map((c) => simulateCitizen(c, policyGrid, c.departureTime, perps));
  }, [allCitizens, policyGrid, perps]);

  // Aggregate Metrics for Baseline & Policy
  const baselineMetrics = useMemo<AggregateMetrics>(() => {
    return calculateAggregateMetrics(baselineResults, allCitizens, baselineGrid, []);
  }, [baselineResults, allCitizens, baselineGrid]);

  const policyMetrics = useMemo<AggregateMetrics>(() => {
    return calculateAggregateMetrics(policyResults, allCitizens, policyGrid, activePolicyIds);
  }, [policyResults, allCitizens, policyGrid, activePolicyIds]);

  // Active grid & results depending on selected mode
  const activeGrid = mode === 'BASELINE' ? baselineGrid : policyGrid;
  const activeResults = mode === 'BASELINE' ? baselineResults : policyResults;
  const activeMetrics = mode === 'BASELINE' ? baselineMetrics : policyMetrics;

  // Count threats deterred by lighting & police
  const threatsDeterred = useMemo(() => {
    return perps.filter((p) => {
      return activeGrid.amenities.some((a) => {
        const isDeterrent = a.type === 'STREETLIGHT' || a.type === 'POLICE_KIOSK';
        if (!isDeterrent) return false;
        const d = Math.hypot(a.position.x - p.position.x, a.position.y - p.position.y);
        return d <= (a.type === 'POLICE_KIOSK' ? 4.2 : a.radius * 1.2);
      });
    }).length;
  }, [perps, activeGrid.amenities]);

  const customCounts = useMemo(() => {
    return {
      streetlights: userPlacedAmenities.filter((a) => a.type === 'STREETLIGHT').length,
      policeKiosks: userPlacedAmenities.filter((a) => a.type === 'POLICE_KIOSK').length,
      perps: perps.filter((p) => p.isCustomPlaced).length,
      busStops: userPlacedAmenities.filter((a) => a.type === 'BUS_STOP').length,
      restrooms: userPlacedAmenities.filter((a) => a.type === 'PUBLIC_TOILET').length,
    };
  }, [userPlacedAmenities, perps]);

  // Manual tile click for placing or bulldozing features
  const handleTileClick = useCallback(
    (pos: Position) => {
      if (selectedTool === 'STREETLIGHT') {
        const newLamp: Amenity = {
          id: `custom-lamp-${Date.now()}`,
          type: 'STREETLIGHT',
          position: pos,
          radius: 2.5,
          activeHours: [18, 6],
          name: `Custom Lamp (${pos.x}, ${pos.y})`,
          description: 'User placed streetlight',
          capex: 1200,
          monthlyOpex: 25,
          isPolicyAdded: true,
        };
        setUserPlacedAmenities((prev) => [...prev, newLamp]);
        confetti({ particleCount: 30, spread: 50, origin: { y: 0.85 } });
      } else if (selectedTool === 'POLICE_KIOSK') {
        const newKiosk: Amenity = {
          id: `custom-police-${Date.now()}`,
          type: 'POLICE_KIOSK',
          position: pos,
          radius: 4.0,
          activeHours: [0, 24],
          name: `Police SOS Booth (${pos.x}, ${pos.y})`,
          description: 'Emergency security and anti-perp beacon',
          capex: 6500,
          monthlyOpex: 350,
          isPolicyAdded: true,
        };
        setUserPlacedAmenities((prev) => [...prev, newKiosk]);
        confetti({ particleCount: 45, spread: 60, origin: { y: 0.85 } });
      } else if (selectedTool === 'PERP') {
        const newPerp: PerpPersona = {
          id: `custom-perp-${Date.now()}`,
          name: `Suspicious Lurker (${pos.x}, ${pos.y})`,
          position: pos,
          threatRadius: 2.5,
          state: 'LURKING',
          speechText: 'Waiting in dark shadows 🦹',
          isCustomPlaced: true,
        };
        setPerps((prev) => [...prev, newPerp]);
      } else if (selectedTool === 'BUS_STOP') {
        const newStop: Amenity = {
          id: `custom-bus-${Date.now()}`,
          type: 'BUS_STOP',
          position: pos,
          radius: 1.5,
          activeHours: [0, 24],
          name: `Bus Stop (${pos.x}, ${pos.y})`,
          description: 'Safe transit stop',
          capex: 4500,
          monthlyOpex: 120,
          isPolicyAdded: true,
        };
        setUserPlacedAmenities((prev) => [...prev, newStop]);
      } else if (selectedTool === 'RESTROOM') {
        const newRestroom: Amenity = {
          id: `custom-restroom-${Date.now()}`,
          type: 'PUBLIC_TOILET',
          position: pos,
          radius: 1.5,
          activeHours: [0, 24],
          name: `Restroom Pod (${pos.x}, ${pos.y})`,
          description: 'Public accessible restroom',
          capex: 18000,
          monthlyOpex: 400,
          isPolicyAdded: true,
        };
        setUserPlacedAmenities((prev) => [...prev, newRestroom]);
      } else if (selectedTool === 'DEMOLISH') {
        setUserPlacedAmenities((prev) =>
          prev.filter((a) => a.position.x !== pos.x || a.position.y !== pos.y)
        );
        setPerps((prev) =>
          prev.filter((p) => p.position.x !== pos.x || p.position.y !== pos.y)
        );
      }
    },
    [selectedTool]
  );

  const handleResetCustom = () => {
    setUserPlacedAmenities([]);
    setPerps(INITIAL_PERPS);
  };

  const handleSimulate = () => {
    confetti({
      particleCount: 80,
      spread: 70,
      origin: { y: 0.7 },
    });
    // Automatically switch to dashboard tab to see the impact
    setSidebarTab('DASHBOARD');
  };

  const selectedCitizen = allCitizens.find((c) => c.id === selectedCitizenId) || null;
  const selectedBaselineRes = baselineResults.find((r) => r.personaId === selectedCitizenId) || null;
  const selectedPolicyRes = policyResults.find((r) => r.personaId === selectedCitizenId) || null;

  return (
    <div className="app-layout">
      {/* Top Navigation & KPI Header */}
      <Header
        currentScenarioTitle={scenario.title}
        currentHour={currentHour}
        mode={mode}
        onSetMode={(m) => {
          setMode(m);
          if (m === 'COMPARISON') setSidebarTab('DASHBOARD');
          if (m === 'POLICY') setSidebarTab('POLICIES');
        }}
        metrics={activeMetrics}
        baselineMetrics={baselineMetrics}
        onOpenGeminiModal={() => setIsGeminiModalOpen(true)}
      />

      {/* Main Interactive Workspace */}
      <div className="main-workspace">
        {/* Left Side: 3D Canvas & Simulation Visualizer */}
        <div className="canvas-column">
          {/* Top Interactive Architect & Crime Sandbox Toolbar */}
          <ArchitectToolbar
            selectedTool={selectedTool}
            onSelectTool={setSelectedTool}
            onResetCustom={handleResetCustom}
            customCounts={customCounts}
            threatCount={perps.length}
            threatsDeterred={threatsDeterred}
          />

          <div className="canvas-wrapper">
            <NeighborhoodCanvas
              grid={activeGrid}
              citizens={allCitizens}
              simResults={activeResults}
              perps={perps}
              currentHour={currentHour}
              viewMode={viewMode}
              selectedCitizenId={selectedCitizenId}
              onSelectCitizen={setSelectedCitizenId}
              onTileClick={handleTileClick}
              selectedTool={selectedTool}
            />

            {/* Floating Overlay Info Tag */}
            <div className="floating-info-badge">
              <span className="dot-pulse" />
              <span>
                {mode === 'BASELINE'
                  ? 'Status Quo: Unlit Alleys & 21:00 Bus Cutoff (Fear High)'
                  : mode === 'COMPARISON'
                  ? 'Comparing Status Quo vs Policy Interventions'
                  : 'Policy Sandbox: Streetlights & Night Transit Active'}
              </span>
            </div>
          </div>

          {/* Time & Playback Scrubber Bar */}
          <TimeScrubber
            currentHour={currentHour}
            onSetHour={setCurrentHour}
            isPlaying={isPlaying}
            onTogglePlay={() => setIsPlaying((p) => !p)}
            speed={speed}
            onSetSpeed={setSpeed}
            viewMode={viewMode}
            onSetViewMode={setViewMode}
          />
        </div>

        {/* Right Side: Policy Toolbar & Civic Dashboard */}
        <div className="sidebar-column">
          {/* Segmented Control for Right Sidebar */}
          {mode !== 'BASELINE' && (
            <div className="sidebar-tab-switcher">
              <button
                className={`sidebar-tab-btn ${sidebarTab === 'POLICIES' ? 'active' : ''}`}
                onClick={() => setSidebarTab('POLICIES')}
              >
                <Sliders size={15} />
                <span>Policy Controls ({activePolicyIds.length})</span>
              </button>
              <button
                className={`sidebar-tab-btn ${sidebarTab === 'DASHBOARD' ? 'active' : ''}`}
                onClick={() => setSidebarTab('DASHBOARD')}
              >
                <BarChart3 size={15} />
                <span>Civic Impact Dashboard</span>
              </button>
            </div>
          )}

          {/* Render Active View in Sidebar */}
          {sidebarTab === 'POLICIES' && mode !== 'BASELINE' ? (
            <PolicyToolbar
              policies={AVAILABLE_POLICIES}
              activePolicyIds={activePolicyIds}
              onTogglePolicy={handleTogglePolicy}
              onApplyRecommended={handleApplyRecommended}
              onSimulate={handleSimulate}
              selectedTool={selectedTool}
              onSelectTool={(tool) => setSelectedTool((tool as ArchitectTool) || 'INSPECT')}
              totalCapEx={policyMetrics.totalCapEx}
              monthlyOpEx={policyMetrics.monthlyOpEx}
            />
          ) : (
            <CivicDashboard
              baselineMetrics={baselineMetrics}
              policyMetrics={policyMetrics}
              citizens={allCitizens}
              baselineResults={baselineResults}
              policyResults={policyResults}
              onSelectCitizen={setSelectedCitizenId}
            />
          )}
        </div>
      </div>

      {/* Citizen Deep-Dive Modal */}
      <CitizenInspectorModal
        citizen={selectedCitizen}
        baselineResult={selectedBaselineRes}
        policyResult={selectedPolicyRes}
        onClose={() => setSelectedCitizenId(null)}
      />

      {/* Gemini AI Policy Advisor Modal */}
      {isGeminiModalOpen && (
        <GeminiPolicyAdvisorModal
          scenario={scenario}
          activePolicies={AVAILABLE_POLICIES.filter((p) => activePolicyIds.includes(p.id))}
          baselineMetrics={baselineMetrics}
          policyMetrics={policyMetrics}
          onAddCitizen={(newCitizen) => {
            setCustomCitizens((prev) => [...prev, newCitizen]);
            confetti({ particleCount: 70, spread: 70, origin: { y: 0.6 } });
          }}
          onClose={() => setIsGeminiModalOpen(false)}
        />
      )}
    </div>
  );
}

export default App;
